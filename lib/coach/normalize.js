// Фрагменты внутри слова.
const STEMS = [
  [/тр[еи]н[еи]р[оа]вк/g, 'тренировк'],
  [/(^|[^а-я])не\s*хачу/g, '$1не хочу'],
  [/хачу/g, 'хочу'],
  [/сигодн/g, 'сегодн'],
  [/пожалуста/g, 'пожалуйста'],
  [/спасиб[оа]{2,}/g, 'спасибо'],
];

const KEEP = /[^a-zа-я0-9%°+\-'\s\u{1F600}-\u{1F64F}\u{1F44D}\u{1F44C}]/gu;

export function normalize(text) {
  let s = String(text == null ? '' : text).toLowerCase().replace(/ё/g, 'е');
  s = s.replace(/[’‘`´]/g, "'");
  s = s.replace(/[‐-―−]/g, '-');
  s = s.replace(/([a-zа-я])\1{2,}/g, '$1'); // «спасибооо» → «спасибо», «аааа» → «а»
  for (const [rx, to] of STEMS) s = s.replace(rx, to);
  s = s.replace(KEEP, ' ');
  // дефис остаётся только внутри слов и чисел («что-нибудь», «-5»)
  s = s.replace(/(^|\s)-+(?=\s|$)/g, ' ').replace(/(\S)-+(?=\s|$)/g, '$1');
  s = s.split(/\s+/).filter(Boolean).map((w) => (WORDS[w] != null ? WORDS[w] : w)).join(' ');
  s = s.replace(/потомучто/g, 'потому что');
  return s.trim();
}

export const tokensOf = (norm) => (norm ? norm.split(' ') : []);
