function run(dlg) {
  const { res, wx, tone, en } = dlg.fx;
  setLang(en ? 'en' : 'ru');
  setCoachWeather(W[wx].set());
  let session = {};
  const history = [];
  const lines = [];
  for (const q of dlg.turns) {
    const r = reply(q, RES[res], {}, { history: history.slice(), session, tone });
    session = r.session;
    history.push({ from: 'me', text: [q] }, { from: 'coach', text: r.text, humorId: r.humorId });
    lines.push({ q, a: r.text.join(' ') , raw: r.text });
  }
  setCoachWeather(null);
  setLang('ru');
  return lines;
}

